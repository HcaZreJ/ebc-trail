"""按天配色：地形图与海拔剖面图共用这一份，同一天在两张图里是同一个颜色。

Day 1（加都）与 Day 12（转场回加都）没有徒步轨迹，不在这份配色表里。

第一约束是**相邻两天必须一眼分得开**：读者在地图上顺着一条线往前走、在剖面图上从左往右扫，
判断「这一段是 Day 几」靠的是与前后两段的色差，Day N 徽标只是复核手段。因此同族内的
相邻天在明度上交替（亮—暗—亮—暗），色相也跳开，而不是沿色带平滑过渡。定量判据：
按行程顺序相邻的两天 CIEDE2000 色差 ΔE >= 28，任意两天 ΔE >= 15。

在这个约束之上保留冷暖分族，让地图上并排的两条线一眼看出哪条在上山、哪条在下撤：

- 上山日用暖色（金黄、赭褐、橙、正红、玫红、深绛）
- 海拔适应日（Dingboche）用紫色，它不推进行程、只上去再下来，是另一类日子
- 下撤日用冷色（青绿、墨绿、钴蓝）

上山日与下撤日走同一条走廊，在地图上把两族分别向两侧平移，两条都看得见。

选色约束来自 OpenTopoMap 底图：底图用蓝画河流冰川、用黄绿到橙红棕的色带画海拔，
所以详图先把底图压成低饱和浅色（见 scripts/make_map.py 里 mute() 的参数），
腾出色相空间给这 10 个颜色。
"""

ASCENT_DAYS = (2, 3, 4, 5, 7, 8)
ACCLIMATIZE_DAYS = (6,)
DESCENT_DAYS = (9, 10, 11)

DAY_COLORS = {
    2: (245, 183, 20),    # 亮金黄
    3: (120, 70, 28),     # 深赭褐
    4: (245, 140, 20),    # 亮橙
    5: (178, 26, 34),     # 深正红
    7: (233, 92, 148),    # 亮玫红
    8: (135, 20, 58),     # 深绛
    6: (98, 52, 168),     # 深紫：海拔适应日（Dingboche）
    9: (0, 186, 178),     # 亮青绿：下撤日
    10: (14, 92, 66),     # 深墨绿
    11: (48, 136, 228),   # 亮钴蓝
}

# 「可走的线路」底层：大环线全部导航线画成近黑，退到计划路线之后，
# 同时与浅色底图和其余灰阶元素拉开对比
OPTION_LINE = (31, 31, 30)


def hex_color(day):
    """matplotlib 用的 #rrggbb 字符串。"""
    r, g, b = DAY_COLORS[day]
    return f"#{r:02x}{g:02x}{b:02x}"


def family(day):
    """该天属于哪一族：'ascent' / 'acclimatize' / 'descent'。"""
    if day in ACCLIMATIZE_DAYS:
        return "acclimatize"
    if day in DESCENT_DAYS:
        return "descent"
    return "ascent"
